create table if not exists public.sources (
  source_type text primary key,
  display_name text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.documents (
  id text primary key,
  source_type text not null references public.sources(source_type),
  external_id text not null,
  title text not null,
  body text not null default '',
  url text not null,
  author text,
  published_at timestamptz,
  collected_at timestamptz not null,
  language text not null default 'unknown',
  raw_payload jsonb not null default '{}'::jsonb,
  source_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (source_type, external_id)
);

create index if not exists documents_source_published_at_idx
  on public.documents (source_type, published_at desc);

create index if not exists documents_collected_at_idx
  on public.documents (collected_at desc);

create table if not exists public.document_relations (
  id bigint generated by default as identity primary key,
  parent_document_id text not null references public.documents(id) on delete cascade,
  child_document_id text not null references public.documents(id) on delete cascade,
  relation_type text not null,
  created_at timestamptz not null default now(),
  unique (parent_document_id, child_document_id, relation_type)
);

create table if not exists public.document_analysis (
  id bigint generated by default as identity primary key,
  document_id text not null references public.documents(id) on delete cascade,
  analysis_type text not null,
  model text not null,
  result jsonb not null default '{}'::jsonb,
  analyzed_at timestamptz not null default now(),
  unique (document_id, analysis_type, model)
);

