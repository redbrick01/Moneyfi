CREATE SCHEMA IF NOT EXISTS equity_research;

CREATE TABLE IF NOT EXISTS equity_research.companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticker TEXT NOT NULL,
  exchange TEXT,
  company_name TEXT NOT NULL,
  sector TEXT,
  industry TEXT,
  currency TEXT DEFAULT 'USD',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (ticker, exchange)
);

CREATE TABLE IF NOT EXISTS equity_research.research_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES equity_research.companies(id) ON DELETE CASCADE,
  report_slug TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  report_type TEXT NOT NULL DEFAULT 'integrated_public_research',
  report_date DATE NOT NULL,
  as_of_date DATE,
  author TEXT,
  language TEXT NOT NULL DEFAULT 'ko',
  source_markdown_path TEXT,
  summary TEXT,
  one_line_conclusion TEXT,
  investment_stance TEXT,
  confidence_level TEXT,
  is_investment_advice BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS equity_research.report_sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  parent_section_id BIGINT REFERENCES equity_research.report_sections(id) ON DELETE CASCADE,
  section_no TEXT,
  title TEXT NOT NULL,
  section_type TEXT,
  sort_order INTEGER NOT NULL,
  body TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (report_id, section_no)
);

CREATE TABLE IF NOT EXISTS equity_research.source_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_name TEXT NOT NULL,
  publisher TEXT,
  analyst_or_author TEXT,
  document_title TEXT NOT NULL,
  document_type TEXT,
  published_date DATE,
  url TEXT,
  access_type TEXT DEFAULT 'public',
  source_quality_grade TEXT CHECK (source_quality_grade IN ('A', 'B', 'C', 'D')),
  stance TEXT,
  rating TEXT,
  price_target NUMERIC,
  price_target_currency TEXT DEFAULT 'USD',
  price_target_previous NUMERIC,
  fair_value NUMERIC,
  fair_value_currency TEXT DEFAULT 'USD',
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (publisher, document_title, published_date)
);

CREATE TABLE IF NOT EXISTS equity_research.report_source_documents (
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  source_document_id BIGINT NOT NULL REFERENCES equity_research.source_documents(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'primary',
  sort_order INTEGER,
  PRIMARY KEY (report_id, source_document_id)
);

CREATE TABLE IF NOT EXISTS equity_research.source_claims (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_document_id BIGINT NOT NULL REFERENCES equity_research.source_documents(id) ON DELETE CASCADE,
  claim_type TEXT NOT NULL,
  claim_text TEXT NOT NULL,
  metric_name TEXT,
  metric_value NUMERIC,
  metric_unit TEXT,
  currency TEXT,
  period_label TEXT,
  evidence_note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS equity_research.company_metrics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  metric_name TEXT NOT NULL,
  metric_value NUMERIC,
  metric_text TEXT,
  metric_unit TEXT,
  currency TEXT,
  fiscal_period TEXT,
  period_end_date DATE,
  yoy_change_pct NUMERIC,
  qoq_change_pct NUMERIC,
  source_document_id BIGINT REFERENCES equity_research.source_documents(id) ON DELETE SET NULL,
  notes TEXT,
  UNIQUE (report_id, metric_name, fiscal_period, source_document_id)
);

CREATE TABLE IF NOT EXISTS equity_research.investment_theses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  thesis_side TEXT NOT NULL CHECK (thesis_side IN ('bull', 'bear', 'neutral', 'monitoring')),
  title TEXT NOT NULL,
  thesis_text TEXT NOT NULL,
  importance_score INTEGER CHECK (importance_score BETWEEN 1 AND 5),
  source_document_id BIGINT REFERENCES equity_research.source_documents(id) ON DELETE SET NULL,
  sort_order INTEGER
);

CREATE TABLE IF NOT EXISTS equity_research.risks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  risk_category TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  probability_level TEXT,
  impact_level TEXT,
  time_horizon TEXT,
  mitigation_or_watchpoint TEXT,
  source_document_id BIGINT REFERENCES equity_research.source_documents(id) ON DELETE SET NULL,
  sort_order INTEGER
);

CREATE TABLE IF NOT EXISTS equity_research.catalysts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  catalyst_category TEXT,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  expected_timing TEXT,
  expected_direction TEXT CHECK (expected_direction IN ('positive', 'negative', 'mixed', 'unknown')),
  source_document_id BIGINT REFERENCES equity_research.source_documents(id) ON DELETE SET NULL,
  sort_order INTEGER
);

CREATE TABLE IF NOT EXISTS equity_research.valuation_views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  source_document_id BIGINT REFERENCES equity_research.source_documents(id) ON DELETE SET NULL,
  valuation_method TEXT,
  stance TEXT,
  rating TEXT,
  price_at_analysis NUMERIC,
  target_price NUMERIC,
  target_price_low NUMERIC,
  target_price_high NUMERIC,
  fair_value NUMERIC,
  implied_upside_pct NUMERIC,
  currency TEXT DEFAULT 'USD',
  time_horizon TEXT,
  key_assumptions TEXT,
  notes TEXT
);

CREATE TABLE IF NOT EXISTS equity_research.consensus_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  provider TEXT NOT NULL,
  snapshot_date DATE NOT NULL,
  analyst_count INTEGER,
  consensus_rating TEXT,
  average_target_price NUMERIC,
  median_target_price NUMERIC,
  low_target_price NUMERIC,
  high_target_price NUMERIC,
  current_price NUMERIC,
  implied_upside_pct NUMERIC,
  currency TEXT DEFAULT 'USD',
  source_url TEXT,
  UNIQUE (report_id, provider, snapshot_date)
);

CREATE TABLE IF NOT EXISTS equity_research.scenarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  scenario_name TEXT NOT NULL CHECK (scenario_name IN ('bull', 'base', 'bear')),
  scenario_title TEXT,
  summary TEXT,
  valuation_anchor TEXT,
  expected_outcome TEXT,
  sort_order INTEGER,
  UNIQUE (report_id, scenario_name)
);

CREATE TABLE IF NOT EXISTS equity_research.scenario_assumptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id BIGINT NOT NULL REFERENCES equity_research.scenarios(id) ON DELETE CASCADE,
  assumption_category TEXT,
  assumption_text TEXT NOT NULL,
  metric_name TEXT,
  metric_value NUMERIC,
  metric_unit TEXT,
  sort_order INTEGER
);

CREATE TABLE IF NOT EXISTS equity_research.monitoring_indicators (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  area TEXT NOT NULL,
  indicator_name TEXT NOT NULL,
  positive_signal TEXT,
  negative_signal TEXT,
  check_frequency TEXT,
  source_hint TEXT,
  sort_order INTEGER
);

CREATE TABLE IF NOT EXISTS equity_research.reusable_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_name TEXT NOT NULL UNIQUE,
  template_version TEXT NOT NULL DEFAULT '1.0',
  description TEXT,
  template_body TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS equity_research.report_tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES equity_research.research_reports(id) ON DELETE CASCADE,
  tag TEXT NOT NULL,
  UNIQUE (report_id, tag)
);

CREATE TABLE IF NOT EXISTS equity_research.report_search (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT,
  body TEXT,
  source_type TEXT,
  search_vector TSVECTOR GENERATED ALWAYS AS (
    to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(body, ''))
  ) STORED
);

CREATE TABLE IF NOT EXISTS equity_research.report_search_refs (
  search_id BIGINT PRIMARY KEY REFERENCES equity_research.report_search(id) ON DELETE CASCADE,
  entity_type TEXT NOT NULL,
  entity_id BIGINT NOT NULL,
  report_id BIGINT REFERENCES equity_research.research_reports(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_equity_research_reports_company_date ON equity_research.research_reports(company_id, report_date DESC);
CREATE INDEX IF NOT EXISTS idx_equity_research_sections_report_order ON equity_research.report_sections(report_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_equity_research_sources_published_date ON equity_research.source_documents(published_date DESC);
CREATE INDEX IF NOT EXISTS idx_equity_research_source_claims_source ON equity_research.source_claims(source_document_id, claim_type);
CREATE INDEX IF NOT EXISTS idx_equity_research_metrics_report_name ON equity_research.company_metrics(report_id, metric_name);
CREATE INDEX IF NOT EXISTS idx_equity_research_theses_report_side ON equity_research.investment_theses(report_id, thesis_side);
CREATE INDEX IF NOT EXISTS idx_equity_research_risks_report_category ON equity_research.risks(report_id, risk_category);
CREATE INDEX IF NOT EXISTS idx_equity_research_monitoring_report_area ON equity_research.monitoring_indicators(report_id, area);
CREATE INDEX IF NOT EXISTS idx_equity_research_report_search_vector ON equity_research.report_search USING GIN(search_vector);

